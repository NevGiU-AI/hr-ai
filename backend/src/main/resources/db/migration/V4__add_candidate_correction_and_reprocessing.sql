ALTER TABLE candidate_evaluations
    ADD COLUMN IF NOT EXISTS invalidated_at timestamp(6) with time zone;

ALTER TABLE candidates
    ALTER COLUMN email TYPE varchar(320);

ALTER TABLE cv_documents
    ADD COLUMN IF NOT EXISTS reprocessed_at timestamp(6) with time zone;

CREATE TABLE IF NOT EXISTS candidate_metadata_revisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id varchar(100) NOT NULL,
    candidate_id bigint NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
    actor_user_id bigint NOT NULL,
    actor_email varchar(320) NOT NULL,
    name varchar(255),
    email varchar(320),
    location varchar(255),
    current_title varchar(255),
    years_experience integer,
    created_at timestamp(6) with time zone NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_candidate_metadata_revisions_candidate
    ON candidate_metadata_revisions (organization_id, candidate_id, created_at DESC, id DESC);

ALTER TABLE cv_documents
    ADD COLUMN IF NOT EXISTS extraction_method varchar(16) NOT NULL DEFAULT 'NATIVE',
    ADD COLUMN IF NOT EXISTS extraction_confidence double precision;

CREATE TABLE IF NOT EXISTS cv_document_pages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id bigint NOT NULL REFERENCES cv_documents(id) ON DELETE CASCADE,
    page_number integer NOT NULL,
    extracted_text oid NOT NULL,
    confidence double precision NOT NULL,
    CONSTRAINT uk_cv_document_pages_document_page UNIQUE (document_id, page_number),
    CONSTRAINT ck_cv_document_pages_page_number CHECK (page_number > 0),
    CONSTRAINT ck_cv_document_pages_confidence CHECK (confidence >= 0 AND confidence <= 100)
);

CREATE INDEX IF NOT EXISTS idx_cv_document_pages_document
    ON cv_document_pages (document_id, page_number);
